import { z } from 'zod';

export const manifestSchema = z.object({
  generatedAt: z.string().datetime(),
  source: z.string().url(),
  commit: z.string(),
  buildId: z.string().optional(),
  site: z.record(z.string(), z.unknown()).optional(),
  nodes: z.array(z.object({
    id: z.string().min(1),
    path: z.string(),
    name: z.string(),
    type: z.enum(['dir', 'file']),
    ext: z.string(),
    language: z.string(),
    size: z.number().nonnegative(),
    lines: z.number().int().nonnegative().nullable(),
    lastCommit: z.object({ date: z.string().nullable(), hash: z.string().nullable(), message: z.string().nullable() }),
    firstCommit: z.object({ date: z.string().nullable(), hash: z.string().nullable(), message: z.string().nullable() }),
    githubUrl: z.string().url(),
    rawUrl: z.string().url().nullable(),
    editUrl: z.string().url(),
    githubDevUrl: z.string().url(),
    topic: z.string().nullable(),
    tags: z.array(z.string()),
    title: z.string(),
    status: z.string().nullable(),
    contentFile: z.string().nullable(),
    previewHtml: z.string().nullable().optional(),
    conversionError: z.string().nullable().optional(),
    parentId: z.string().nullable(),
    statement: z.string().nullable(),
    method: z.string().nullable(),
    date: z.string().nullable(),
    workType: z.enum(['HW', 'CW']).nullable(),
  })),
  topics: z.array(z.object({ id: z.string(), title: z.string() })),
});
